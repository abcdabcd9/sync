/**
 * 🔒 安全审计 #26：设备敏感数据保护说明与策略常量
 *
 * 本文件集中声明「数据在设备上如何被保护」的权威说明，供设置页「账号安全」
 * 弹窗、隐私政策文案以及后续安全审计引用。所有描述必须与实际实现保持一致，
 * 修改存储策略时请同步更新本文件。
 *
 * ─────────────────────────────────────────────────────────────
 * 一、数据分级与存储位置
 * ─────────────────────────────────────────────────────────────
 *
 * | 数据类型                        | 存储位置                    | 加密方式                     |
 * | ------------------------------- | --------------------------- | ---------------------------- |
 * | 登录会话（access/refresh token）| AsyncStorage（Supabase SDK）| 系统沙盒隔离                 |
 * | 健康记录、饮水/饮食偏好         | AsyncStorage + Supabase     | 系统沙盒隔离 + 传输 TLS 1.2+ |
 * | 聊天消息、私密媒体              | Supabase（私有桶 + 签名 URL）| 传输 TLS + 7 天签名链接      |
 * | 推送令牌                        | Supabase（push_tokens 表）  | RLS 限定本人可读写           |
 * | 录音临时文件                    | 应用缓存目录                | 系统沙盒隔离，发送后清理     |
 *
 * 说明：iOS 上应用沙盒由系统强制隔离，其他 App 无法读取；Android 上应用私有
 * 目录（/data/data/<package>）同样受 Linux 权限保护。设备若已越狱/Root，
 * 上述隔离可被绕过 —— 这是操作系统层面的风险，App 无法完全防御。
 *
 * ─────────────────────────────────────────────────────────────
 * 二、设备层面的防护措施
 * ─────────────────────────────────────────────────────────────
 *
 * 1. **不落盘敏感明文**：Supabase 的 anon key 通过 EXPO_PUBLIC_* 环境变量注入，
 *    仓库中不含真实密钥（见 .gitignore）。service_role key 永不下发到客户端。
 * 2. **私密媒体不暴露公网**：chat_media 桶已私有化，客户端只持有 7 天有效的
 *    签名 URL（见 useMediaUpload.js 的 createSignedMediaUrl）。
 * 3. **临时文件即用即删**：录音、下载到相册的中间文件在使用后立即 delete()。
 * 4. **退出登录即清空**：signOut 会清除本地会话；注销账号额外精准移除
 *    「当前用户」相关的本地 key（收藏 / 会话偏好等），不再使用
 *    AsyncStorage.clear() 误删全盘数据，其他账号的聊天记录与全局偏好得以保留。
 * 5. **传输全程 HTTPS**：Supabase 与推送服务均强制 TLS，禁止明文回退。
 *
 * ─────────────────────────────────────────────────────────────
 * 三、用户可自行采取的加固措施（建议在隐私政策中告知）
 * ─────────────────────────────────────────────────────────────
 *
 * - 为设备设置锁屏密码 / 生物识别，防止物理接触者读取应用数据。
 * - 开启系统级「设备加密」（iOS 默认开启；Android 需 Android 10+ 且设置锁屏）。
 * - 不要在越狱 / Root 的设备上登录本应用。
 * - 定期在「设置 → 账号安全」中检查登录设备，发现异常立即修改密码。
 * - 公共设备使用后请务必退出登录。
 *
 * ─────────────────────────────────────────────────────────────
 * 四、已知边界（诚实披露，避免过度承诺）
 * ─────────────────────────────────────────────────────────────
 *
 * - 本应用**未**实现端到端加密（E2EE）。消息在服务端以可读形式存储，
 *   受 RLS 与私有桶保护，但服务端运维方在技术上具备访问能力。
 * - 截图、录屏、系统备份（iCloud / Google 备份）不受应用控制。
 * - 已保存到系统相册的媒体脱离应用沙盒，由相册应用与云同步策略管理。
 */

